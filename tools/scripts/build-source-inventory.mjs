import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { probeUrl } from './lib/url-probe.mjs';

/**
 * Measures how much source data the repository is subscribed to, and writes it down.
 *
 * The catalog says which files each research object points at, but not how large they are: size is
 * a fact about the publisher's file, not about our decision to reference it. It can only be
 * learned by asking, and the answer changes whenever an agency reissues a file.
 *
 * So this is an explicit step, not part of the build. It asks every distinct file URL for its
 * length, aggregates by program, and commits the result with the date it was taken. The API serves
 * that artifact, and the UI shows the date alongside the totals, because a byte count with no
 * as-of date is a number pretending to be current.
 *
 * Not in `quality:all`, for the same reason `verify:sources` is not: it depends on federal hosts
 * being reachable, and an agency outage must not read as a broken build.
 *
 * Usage:
 *   node tools/scripts/build-source-inventory.mjs
 *   node tools/scripts/build-source-inventory.mjs --limit 20   a quick partial run while iterating
 */
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const catalogPath = join(
  repoRoot,
  'apps',
  'repository-api',
  'src',
  'main',
  'resources',
  'discovery-fixture-catalog.json',
);
const outputPath = join(
  repoRoot,
  'apps',
  'repository-api',
  'src',
  'main',
  'resources',
  'source-inventory.json',
);

const args = process.argv.slice(2);
const limitIndex = args.indexOf('--limit');
const limit =
  limitIndex === -1 ? Number.POSITIVE_INFINITY : Number(args[limitIndex + 1]);
const CONCURRENCY = 6;

const items = JSON.parse(readFileSync(catalogPath, 'utf8')).items ?? [];

/**
 * One entry per distinct URL, not per file reference.
 *
 * Several research objects legitimately point at the same national file — the USGS earthquake feed
 * is referenced by every area — and counting its bytes once per reference would inflate the total
 * into fiction.
 */
const byUrl = new Map();
for (const item of items) {
  for (const file of item.files ?? []) {
    const existing = byUrl.get(file.url);
    if (existing) {
      existing.programs.add(item.program);
      existing.references += 1;
      continue;
    }

    byUrl.set(file.url, {
      url: file.url,
      format: file.format,
      programs: new Set([item.program]),
      references: 1,
    });
  }
}

const targets = [...byUrl.values()].slice(0, limit);
console.log(
  `Measuring ${targets.length} distinct file URL(s) across ${items.length} research objects.\n`,
);

let index = 0;
const measured = [];

async function worker() {
  while (index < targets.length) {
    const target = targets[index++];
    const outcome = await probeUrl(target.url);
    measured.push({ ...target, ...outcome });
    process.stdout.write(
      outcome.ok ? (outcome.contentLength ? '.' : '?') : 'x',
    );
  }
}

await Promise.all(
  Array.from({ length: Math.min(CONCURRENCY, targets.length) }, worker),
);
process.stdout.write('\n');

const sizeByUrl = new Map(
  measured.map((entry) => [entry.url, entry.contentLength ?? null]),
);
const reachableByUrl = new Map(
  measured.map((entry) => [entry.url, entry.ok === true]),
);

/** Aggregates per program, counting each distinct URL once within that program. */
const programs = new Map();
for (const item of items) {
  const entry = programs.get(item.program) ?? {
    program: item.program,
    objectCount: 0,
    fileCount: 0,
    measuredFileCount: 0,
    unreachableFileCount: 0,
    totalBytes: 0,
    urls: new Set(),
  };

  entry.objectCount += 1;
  for (const file of item.files ?? []) {
    if (entry.urls.has(file.url)) {
      continue;
    }
    entry.urls.add(file.url);
    entry.fileCount += 1;

    const size = sizeByUrl.get(file.url);
    if (size !== undefined && size !== null) {
      entry.measuredFileCount += 1;
      entry.totalBytes += size;
    }
    if (reachableByUrl.get(file.url) === false) {
      entry.unreachableFileCount += 1;
    }
  }

  programs.set(item.program, entry);
}

const byProgram = [...programs.values()]
  .map(({ urls, ...rest }) => rest)
  .sort((left, right) => right.totalBytes - left.totalBytes);

const inventory = {
  $comment:
    'Generated by tools/scripts/build-source-inventory.mjs. Do not edit. Run: pnpm run sources:inventory',
  checkedAt: new Date().toISOString(),
  objectCount: items.length,
  programCount: byProgram.length,
  distinctFileCount: byUrl.size,
  measuredFileCount: byProgram.reduce(
    (total, entry) => total + entry.measuredFileCount,
    0,
  ),
  unreachableFileCount: byProgram.reduce(
    (total, entry) => total + entry.unreachableFileCount,
    0,
  ),
  totalBytes: byProgram.reduce((total, entry) => total + entry.totalBytes, 0),
  byProgram,
};

writeFileSync(outputPath, `${JSON.stringify(inventory, null, 2)}\n`);

const gigabytes = (inventory.totalBytes / 1024 ** 3).toFixed(2);
console.log(
  `\n${inventory.objectCount} objects, ${inventory.programCount} programs, ` +
    `${inventory.distinctFileCount} distinct files.`,
);
// The three tallies must partition the distinct files, or the line invites the reader to add
// them up and get more files than exist. A URL that did not answer is already missing from
// measuredFileCount, so subtracting it once more is what leaves "no length" honest.
const noLengthCount =
  inventory.distinctFileCount -
  inventory.measuredFileCount -
  inventory.unreachableFileCount;
console.log(
  `Measured ${inventory.measuredFileCount} of them: ${gigabytes} GiB. ` +
    `${noLengthCount} answered without a length, ` +
    `${inventory.unreachableFileCount} did not answer.`,
);
console.log(`\nWritten to ${outputPath}`);
